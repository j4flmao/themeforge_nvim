local M = {}

local state = require("themeforge.state")

function M.setup(opts)
  opts = opts or {}

  -- Store config
  state.config = {
    default_theme = opts.default_theme or "tokyonight-storm",
    restore_on_start = opts.restore_on_start ~= false,
    config_paths = opts.config_paths or {},
    default_save_path = opts.default_save_path,
    panel = vim.tbl_extend("force", {
      width_ratio = 0.82,
      height_ratio = 0.82,
      border = "rounded",
    }, opts.panel or {}),
    compat = opts.compat or "auto",
    cache_path = opts.cache_path or (vim.fn.stdpath("data") .. "/themeforge/last.json"),
    autosave_cache = opts.autosave_cache ~= false,
    export_dir = opts.export_dir,
  }

  -- Apply default UI options
  if opts.ui then
    state.current.ui_options = vim.tbl_extend("force", state.current.ui_options, opts.ui)
  end

  -- Plugins lazy-loaded later may change which integrations are present.
  local group = vim.api.nvim_create_augroup("ThemeForgeCompat", { clear = true })
  vim.api.nvim_create_autocmd("User", {
    group = group,
    pattern = { "LazyLoad", "VeryLazy" },
    callback = function() require("themeforge.compat").reset_cache() end,
  })

  -- Restore on start
  if state.config.restore_on_start then
    -- Try session cache first
    local restored = state.load_cache()
    if restored and state.current.active_theme then
      vim.schedule(function()
        local apply = require("themeforge.apply")
        apply.apply()
      end)
    else
      -- Apply default theme
      vim.schedule(function()
        local apply = require("themeforge.apply")
        apply.apply(state.config.default_theme)
      end)
    end
  end
end

function M.open()
  local panel = require("themeforge.ui.panel")
  panel.open()
end

function M.close()
  local panel = require("themeforge.ui.panel")
  panel.close()
end

function M.apply(opts)
  local apply = require("themeforge.apply")
  if type(opts) == "string" then
    state.set_theme(opts)
    local ok = apply.apply(opts)
    if ok then state.record_recent(opts) end
    return ok
  elseif type(opts) == "table" then
    if opts.theme then
      state.set_theme(opts.theme)
    end
    if opts.overrides then
      for group, hl in pairs(opts.overrides) do
        state.set_override(group, hl)
      end
    end
    if opts.colors then
      for key, value in pairs(opts.colors) do
        state.set_color_override(key, value)
      end
    end
    if opts.mix then
      for k, v in pairs(opts.mix) do
        state.set_mix(k, v)
      end
    end
    if opts.ui then
      for k, v in pairs(opts.ui) do
        state.set_ui_option(k, v)
      end
    end
    if opts.lsp_tokens then
      local lsp = require("themeforge.lsp_tokens")
      for name, spec in pairs(opts.lsp_tokens) do
        local group = lsp.normalize_group(name)
        if group then state.set_lsp_token(group, spec) end
      end
    end
    local ok = apply.apply(opts)
    if ok then state.record_recent(state.current.active_theme) end
    return ok
  else
    return apply.apply()
  end
end

function M.doctor()
  return require("themeforge.doctor").run()
end

function M.save(filepath)
  if filepath then
    local writer = require("themeforge.writer")
    return writer.write(filepath)
  else
    local filepicker = require("themeforge.ui.filepicker")
    filepicker.open()
  end
end

--- Export the current theme + blend as a standalone colorscheme file
--- (`colors/<name>.lua`) that works without ThemeForge installed.
function M.export(name, dir)
  name = (name and name ~= "") and name or ("themeforge-" .. (state.current.active_theme or "custom"))
  if not name:match("^[%w_%-%.]+$") then
    vim.notify("[ThemeForge] Invalid colorscheme name: " .. name, vim.log.levels.ERROR)
    return false
  end
  local theme = state.current.active_theme and require("themeforge.themes").get(state.current.active_theme)
  if not theme then
    vim.notify("[ThemeForge] No active theme to export", vim.log.levels.WARN)
    return false
  end
  local highlights, colors = require("themeforge.resolver").resolve(
    theme, state.current.overrides, state.current.ui_options, state.current.palette_mix, state.current.color_overrides,
    state.current.lsp_tokens)
  for group, hl in pairs(require("themeforge.compat").collect(colors, state.config.compat or "auto")) do
    if highlights[group] == nil then highlights[group] = hl end
  end

  local names = vim.tbl_keys(highlights)
  table.sort(names)
  local lines = {
    "-- Generated by ThemeForge.nvim from " .. (theme.name or theme.id),
    "vim.cmd('highlight clear')",
    "if vim.fn.exists('syntax_on') == 1 then vim.cmd('syntax reset') end",
    "vim.o.termguicolors = true",
    "vim.o.background = 'dark'",
    "vim.g.colors_name = " .. string.format("%q", name),
    "local set = vim.api.nvim_set_hl",
  }
  for _, group in ipairs(names) do
    local hl = highlights[group]
    local clean = {}
    for k, v in pairs(hl) do
      if v ~= "NONE" or k == "bg" then clean[k] = v end
    end
    table.insert(lines, string.format("set(0, %q, %s)", group, vim.inspect(clean, { newline = " ", indent = "" })))
  end

  dir = dir or state.config.export_dir or (vim.fn.stdpath("config") .. "/colors")
  vim.fn.mkdir(dir, "p")
  local path = dir .. "/" .. name .. ".lua"
  local f = io.open(path, "w")
  if not f then
    vim.notify("[ThemeForge] Cannot write " .. path, vim.log.levels.ERROR)
    return false
  end
  f:write(table.concat(lines, "\n") .. "\n")
  f:close()
  vim.notify("[ThemeForge] Exported :colorscheme " .. name .. " -> " .. path, vim.log.levels.INFO)
  return path
end

function M.copy()
  local writer = require("themeforge.writer")
  local content = table.concat(writer.generate_block(), "\n")
  vim.fn.setreg("+", content)
  vim.notify("[ThemeForge] Configuration copied to clipboard", vim.log.levels.INFO)
  return content
end

function M.reset()
  state.reset()
  if state.current.active_theme then
    local apply = require("themeforge.apply")
    apply.apply()
  end
end

function M.save_blend(name)
  if not name or name == "" then
    vim.notify("[ThemeForge] Blend name required", vim.log.levels.ERROR)
    return
  end

  local blend_path = vim.fn.stdpath("data") .. "/themeforge/blends.json"
  local dir = vim.fn.fnamemodify(blend_path, ":h")
  if vim.fn.isdirectory(dir) == 0 then
    vim.fn.mkdir(dir, "p")
  end

  -- Load existing blends
  local blends = {}
  local f = io.open(blend_path, "r")
  if f then
    local raw = f:read("*a")
    f:close()
    local ok, data = pcall(vim.fn.json_decode, raw)
    if ok and data then
      blends = data
    end
  end

  -- Save current state as a blend
  blends[name] = {
    base_theme = state.current.active_theme,
    overrides = vim.deepcopy(state.current.overrides),
    colors = vim.deepcopy(state.current.color_overrides),
    lsp_tokens = vim.deepcopy(state.current.lsp_tokens or {}),
    palette_mix = vim.deepcopy(state.current.palette_mix),
    ui_options = vim.deepcopy(state.current.ui_options),
  }

  local wf = io.open(blend_path, "w")
  if wf then
    wf:write(vim.fn.json_encode(blends))
    wf:close()
    vim.notify("[ThemeForge] Blend saved: " .. name, vim.log.levels.INFO)
  end
end

function M.load_blend(name)
  if not name or name == "" then
    vim.notify("[ThemeForge] Blend name required", vim.log.levels.ERROR)
    return false
  end
  local path = vim.fn.stdpath("data") .. "/themeforge/blends.json"
  local f = io.open(path, "r")
  if not f then
    vim.notify("[ThemeForge] No saved blends found", vim.log.levels.WARN)
    return false
  end
  local ok, blends = pcall(vim.fn.json_decode, f:read("*a"))
  f:close()
  local blend = ok and blends and blends[name]
  if not blend then
    vim.notify("[ThemeForge] Blend not found: " .. name, vim.log.levels.ERROR)
    return false
  end

  state.set_theme(blend.base_theme)
  state.current.overrides = blend.overrides or {}
  state.current.color_overrides = blend.colors or {}
  state.current.lsp_tokens = type(blend.lsp_tokens) == "table" and blend.lsp_tokens or {}
  state.current.palette_mix = blend.palette_mix or state.current.palette_mix
  state.current.ui_options = vim.tbl_extend("force", state.current.ui_options, blend.ui_options or {})
  local applied = require("themeforge.apply").apply()
  if applied then
    state.record_recent(state.current.active_theme)
    vim.notify("[ThemeForge] Loaded blend: " .. name, vim.log.levels.INFO)
  end
  return applied
end

function M.list_blends(opts)
  local silent = type(opts) == "table" and opts.silent
  local path = vim.fn.stdpath("data") .. "/themeforge/blends.json"
  local f = io.open(path, "r")
  if not f then
    if not silent then vim.notify("[ThemeForge] No saved blends found", vim.log.levels.INFO) end
    return {}
  end
  local ok, blends = pcall(vim.fn.json_decode, f:read("*a"))
  f:close()
  if not ok or type(blends) ~= "table" then return {} end
  local names = {}
  for name, _ in pairs(blends) do table.insert(names, name) end
  table.sort(names)
  if not silent then
    vim.notify("[ThemeForge] Saved blends:\n  " .. table.concat(names, "\n  "), vim.log.levels.INFO)
  end
  return names
end

function M.apply_profile(name)
  local profiles = {
    focus = {
      ui = { cursorline = false, italic_keywords = false, bold_functions = false, transparency = false },
      mix = { saturation = 42, brightness = 48, opacity = 100 },
    },
    ["high-contrast"] = {
      ui = { cursorline = true, bold_functions = true, bold_cursor = true, transparency = false },
      colors = { fg = "#f2f4f8", fg2 = "#c5cfdf", comment = "#9aa8bd" },
      mix = { saturation = 55, brightness = 52, opacity = 100 },
    },
    ["low-distraction"] = {
      ui = { cursorline = false, italic_keywords = false, bold_functions = false, bold_cursor = false, transparency = false },
      mix = { saturation = 30, brightness = 48, opacity = 100 },
    },
    monochrome = {
      ui = { cursorline = true, italic_keywords = false, bold_functions = true, transparency = false },
      colors = {
        purple = "#c7ccd6", blue = "#c7ccd6", cyan = "#c7ccd6",
        green = "#b7becb", orange = "#d5dae3", red = "#d5dae3", yellow = "#d5dae3",
      },
      mix = { saturation = 0, brightness = 50, opacity = 100 },
    },
  }
  local profile = profiles[name]
  if not profile then
    vim.notify("[ThemeForge] Unknown profile: " .. tostring(name), vim.log.levels.ERROR)
    return false
  end
  local ok = M.apply(profile)
  if ok then vim.notify("[ThemeForge] Profile applied: " .. name, vim.log.levels.INFO) end
  return ok
end

function M.list_profiles()
  return { "focus", "high-contrast", "low-distraction", "monochrome" }
end

function M.random_theme()
  local themes = require("themeforge.themes")
  local ids = themes.ids()
  local candidates = {}
  for _, id in ipairs(ids) do
    if id ~= state.current.active_theme then table.insert(candidates, id) end
  end
  if #candidates == 0 then return false end
  math.randomseed(os.time() + vim.loop.hrtime())
  local id = candidates[math.random(#candidates)]
  local ok = M.apply(id)
  if ok then vim.notify("[ThemeForge] Surprise theme: " .. id, vim.log.levels.INFO) end
  return ok
end

function M.set_compat(mode)
  if mode ~= "auto" and mode ~= "all" and mode ~= "none" then
    vim.notify("[ThemeForge] Compatibility mode must be auto, all, or none", vim.log.levels.ERROR)
    return false
  end
  state.config.compat = mode == "none" and {} or mode
  require("themeforge.compat").reset_cache()
  local ok = require("themeforge.apply").apply()
  if ok then vim.notify("[ThemeForge] Compatibility mode: " .. mode, vim.log.levels.INFO) end
  return ok
end

function M.compat_status()
  local mode = state.config.compat
  if type(mode) == "table" then return "none" end
  return mode or "auto"
end

return M
